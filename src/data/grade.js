// 年级分层数据层（按需加载，不进入首屏主包）。
// 从 content.js 迁出：GRADE_KNOWLEDGE / GRADE_LEARNING 及其访问器、合并题库 getQuiz / quizCountBySubject。
// 说明：getQuiz 依赖 GRADE_LEARNING 做年级合并，故一并迁出，避免 content.js 静态引用本文件，
// 否则 Rollup 会把年级海量数据重新拉回首屏共享块。本文件仅反向引用 content.js 的 QUIZZES（轻量基础题库）。
import { QUIZZES } from './content.js'

// 合并「基础题库 QUIZZES」与「年级分层 GRADE_LEARNING[grade]」的配套练习，形成年级闭环题库。
// grade 缺省时仅返回基础题库（向后兼容旧调用）。每道 GRADE_LEARNING 练习补全溯源字段
// （id / grade / pointId / pointTitle），供错题本记录来源（见 AppContext ANSWER_QUIZ）。
export const getQuiz = (subjectId, grade) => {
  const base = QUIZZES[subjectId] || []
  const points = grade != null ? (GRADE_LEARNING[grade]?.subjects?.[subjectId]?.points || []) : []
  const extra = points.flatMap((p) =>
    (p.exercises || []).map((ex, i) => ({
      ...ex,
      id: ex.id || `${p.id}-e${i}`,
      grade,
      pointId: p.id,
      pointTitle: p.title,
    }))
  )
  return [...base, ...extra]
}

// 统计某学科题目数量；用于空题库边界判断（如某科暂无题目时不渲染练习区）。
export const quizCountBySubject = (subjectId, grade) => getQuiz(subjectId, grade).length;

